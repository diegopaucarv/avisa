-- 1. core.mapa_matriz_excel
--    Mapea cada bloque del Excel de la matriz a un caso de la base.
--
--    POR QUÉ EXISTE: los códigos del Excel (CS-PA-REG-2019-17) usan un esquema
--    distinto del de la base (CS-PA-INF-2025-02), y dos de ellos coinciden por
--    casualidad apuntando a casos distintos. Sin esta tabla el importador no
--    puede saber a qué caso pertenece una fila. Se replica el patrón ya usado
--    en core.cat_mapeo_estado_externo.
-- ============================================================================
CREATE TABLE IF NOT EXISTS core.mapa_matriz_excel (
    id            smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuente        varchar(40) NOT NULL DEFAULT 'MATRIZ_OAIPCS_2026',
    codigo_excel  varchar(40) NULL,
    bloque_fila   integer     NOT NULL,
    caso_id       uuid        NOT NULL REFERENCES core.casos(id) ON DELETE RESTRICT,
    confianza     varchar(10) NOT NULL DEFAULT 'alta'
                  CONSTRAINT chk_mapa_matriz_excel_confianza
                  CHECK (confianza IN ('alta', 'media', 'baja')),
    nota          text,
    creado_en     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_mapa_matriz_excel_fuente_bloque UNIQUE (fuente, bloque_fila)
