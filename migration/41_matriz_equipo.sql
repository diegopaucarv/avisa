    ON core.mapa_matriz_excel (fuente, codigo_excel)
    WHERE codigo_excel IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_mapa_matriz_excel_caso_id
    ON core.mapa_matriz_excel (caso_id);

