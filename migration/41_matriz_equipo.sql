-- ============================================================================
-- 7. Trigger: fecha_ultima_actualizacion automática en core.casos.
--    Sólo BEFORE UPDATE; asigna el valor en NEW (no ejecuta otro UPDATE), así
--    que no puede entrar en recursión. No interviene en INSERT: ahí manda el
--    DEFAULT.
-- ============================================================================
CREATE OR REPLACE FUNCTION core.casos_touch_actualizacion()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW IS DISTINCT FROM OLD THEN
        NEW.fecha_ultima_actualizacion := now();
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_casos_touch_actualizacion ON core.casos;
CREATE TRIGGER trg_casos_touch_actualizacion
    BEFORE UPDATE ON core.casos
    FOR EACH ROW
    EXECUTE FUNCTION core.casos_touch_actualizacion();

COMMENT ON FUNCTION core.casos_touch_actualizacion() IS
    'Mantiene core.casos.fecha_ultima_actualizacion al día en cada UPDATE real de la fila.';

